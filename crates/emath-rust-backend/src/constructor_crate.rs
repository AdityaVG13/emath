//! Constructor-file crate emission (the `emath build` core, shared
//! with the native epoch export).
//!
//! One emitter, two callers: the CLI's `emath build` and the loop
//! host's `export-native` must produce byte-identical artifact crates,
//! so the orchestration lives here once. This module is pure: it takes
//! source text and the spec path (for `use` resolution) and returns
//! the lib text, the manifest, and the admission facts; callers own
//! IO, verification, and presentation.
//!
//! The emission is the self-containment law from `emath build`: the
//! runtime ships inside the artifact as `mod emath_rt` (or, when a
//! function runs in the reference engine, as the vendored `emath-rt`
//! crate beside the engine under `vendor/`), entries carry
//! their authored function names, and authored records map through the
//! backend's carrier-signature interchange (an unmappable field leaves
//! the record unregistered; referencing it refuses by name).

use std::collections::{BTreeMap, BTreeSet};
use std::path::Path;

use emath_core::tree::SyntaxTree;

use crate::codegen_render::{
    EntryAbi, EntryAbiScope, ExactTwinScope, INT_LANE_FAULT, InputKinds, SiblingEntryScope,
    ValueKind, entry_abi, exact_twin_name, internal_entry_name, numeric_boundary_value,
    program_kind, register_entry_abi, substitute_signature_vars,
};
use crate::{emit_constructor_entry_abi, emit_record_definitions, AuthoredRecord};

/// What one constructor-file emission produced.
#[derive(Clone, Debug)]
pub struct ConstructorCrateEmission {
    /// `src/lib.rs` body (self-contained: `mod emath_rt` embedded when
    /// the lowering used the runtime).
    pub lib: String,
    /// `Cargo.toml` body (empty dependency list unless the crate links
    /// the reference engine, which it then carries under `vendor/`).
    pub manifest: String,
    /// The crate name inside the manifest (the sanitized file stem).
    pub package_name: String,
    /// False when any entry lowered to unresolved symbolic code.
    pub runnable: bool,
    /// The main file's function entries, in declaration order.
    pub functions: Vec<String>,
    /// Why entries are not runnable, when they are not.
    pub unresolved: Vec<String>,
    /// The authored records the emission registered, with their
    /// AUTHORED (emath) field names and carrier signatures. The
    /// emitted Rust escapes keywords (`move` becomes `move_` via
    /// `escape_ident`), and that escape is not injective, so
    /// consumers that must recover the authored names (the native
    /// epoch export's scratch mirror) map back through THIS list,
    /// never by heuristic.
    pub records: Vec<AuthoredRecord>,
    /// Whether some function runs in the reference engine, so the crate
    /// carries the engine's source (`files` lists it).
    pub links_engine: bool,
}

/// The reference engine's crates (`ENGINE_FILES`, paths relative to
/// `vendor/`) and the lockfile packages they reach, generated by
/// `build.rs`.
mod engine_vendor {
    include!(concat!(env!("OUT_DIR"), "/engine_vendor.rs"));
}

impl ConstructorCrateEmission {
    /// Every file of the crate, as (path relative to the crate root,
    /// contents): `src/lib.rs`, `Cargo.toml`, and, when it links the
    /// engine, the vendored engine and a `Cargo.lock` pinning the
    /// third-party versions the engine was built and tested with.
    pub fn files(&self) -> Vec<(String, std::borrow::Cow<'_, str>)> {
        let mut files = vec![
            ("src/lib.rs".to_string(), self.lib.as_str().into()),
            ("Cargo.toml".to_string(), self.manifest.as_str().into()),
        ];
        if self.links_engine {
            files.push(("Cargo.lock".to_string(), self.engine_lock().into()));
            files.extend(
                engine_vendor::ENGINE_FILES
                    .iter()
                    .map(|(path, text)| (format!("vendor/{path}"), (*text).into())),
            );
        }
        files
    }

    /// The vendored engine's lockfile packages plus this crate's own
    /// entry, in Cargo's name order, so a build leaves it unchanged.
    fn engine_lock(&self) -> String {
        let mut needs = vec!["emath-exec-ir"];
        if self.lib.contains("emath_rt::") {
            needs.push("emath-rt");
        }
        let own = format!(
            "[[package]]\nname = \"{}\"\nversion = \"0.1.0\"\ndependencies = [\n{}]\n",
            self.package_name,
            needs.iter().map(|need| format!(" \"{need}\",\n")).collect::<String>()
        );
        let mut packages: Vec<(&str, &str)> = engine_vendor::ENGINE_LOCK_PACKAGES.to_vec();
        packages.push((&self.package_name, &own));
        packages.sort_by_key(|(name, _)| *name);
        let blocks: Vec<&str> = packages.iter().map(|(_, block)| *block).collect();
        format!("{}{}", engine_vendor::ENGINE_LOCK_HEADER, blocks.join("\n"))
    }
}

/// A typed refusal from crate emission; callers keep their own
/// presentation (the CLI's E-codes, the loop host's `loop_export_*`).
#[derive(Clone, Debug)]
pub enum ConstructorEmitRefusal {
    /// The source is not a constructor program (or has no function
    /// entries to emit); the text is the refusal message.
    NotConstructor(&'static str),
    /// Merging `use` imports refused; `e_code` is the admission-code
    /// mapping of the engine's own code.
    ImportsRefused { e_code: String, detail: String },
}

/// The gate message for non-constructor source.
const NOT_CONSTRUCTOR: &str =
    "`emath build` emits constructor functions. Write `emath object`, `emath function`, or `emath query`.";

/// The gate message for function-less source.
const NO_FUNCTIONS: &str =
    "`emath build` emits lowered Rust for `emath function` entries. Symbolic query-only files are not marked runnable.";

/// Generated-artifact lint policy: entry names follow authored
/// spellings (`PascalCase`), the flattener parenthesizes substituted
/// expressions defensively, and authored-but-unused parameters stay
/// in signatures - all style-only in machine-generated code.
const EMITTED_HEADER: &str = "#![forbid(unsafe_code)]\n#![allow(nonstandard_style, unused_parens, unused_braces, unused_mut, unused_variables)]\n\n";

/// Emit a prepared module without rereading its root or imports. Hosts supply
/// the root source bytes from the same semantic check that returned `module`.
/// Preparation alone is not full semantic admission; that belongs to sema.
///
/// # Errors
/// A typed [`ConstructorEmitRefusal`]; never a partial crate.
pub fn emit_constructor_crate(
    module: &emath_exec_ir::constructor_layer::PreparedModule,
    spec_path: &Path,
    source: &str,
) -> Result<ConstructorCrateEmission, ConstructorEmitRefusal> {
    let main = module.tree();
    let constructor_only = main.items.iter().all(|item| match item {
        emath_core::tree::Item::Use { .. } => true,
        emath_core::tree::Item::Declaration(decl) => {
            matches!(decl.as_kind.as_str(), "object" | "function" | "query")
        }
        _ => true,
    });
    if !constructor_only {
        return Err(ConstructorEmitRefusal::NotConstructor(NOT_CONSTRUCTOR));
    }
    // Merge `use` imports into one whole-program tree (the engine's
    // install order) so imported objects and functions lower here too.
    // The MAIN file's functions are the crate's entries; imported
    // declarations join as lowering context (siblings, record
    // layouts), never as re-emitted entries.
    let tree = match module.merged_tree() {
        Ok(tree) => tree,
        Err(error) => {
            return Err(ConstructorEmitRefusal::ImportsRefused {
                e_code: emath_exec_ir::constructor_layer::constructor_admit_code(&error.code)
                    .to_string(),
                detail: format!("{}: {}", error.code, error.message),
            });
        }
    };
    let functions: Vec<String> = main
        .items
        .iter()
        .filter_map(|item| match item {
            emath_core::tree::Item::Declaration(decl) if decl.as_kind == "function" => {
                Some(decl.name.clone())
            }
            _ => None,
        })
        .collect();
    if functions.is_empty() {
        return Err(ConstructorEmitRefusal::NotConstructor(NO_FUNCTIONS));
    }
    // Authored records: every object's representation fields in the
    // backend's carrier-signature interchange. An object with a field
    // the interchange cannot map is left unregistered - referencing it
    // then refuses with the named no-layout error instead of guessing.
    let objects: BTreeSet<String> = tree
        .items
        .iter()
        .filter_map(|item| match item {
            emath_core::tree::Item::Declaration(decl) if decl.as_kind == "object" => {
                Some(decl.name.clone())
            }
            _ => None,
        })
        .collect();
    let mut records = Vec::new();
    let mut templates = std::collections::BTreeMap::new();
    for item in &tree.items {
        let emath_core::tree::Item::Declaration(decl) = item else {
            continue;
        };
        if decl.as_kind == "object" && !decl.generics.is_empty() {
            // A generic object has no layout of its own; each
            // instantiation substitutes its carriers into these fields.
            let params: Vec<String> =
                decl.generics.iter().map(|generic| generic.name.clone()).collect();
            let fields = emath_exec_ir::constructor_emir::section_typed_fields(decl, "representation")
                .into_iter()
                .map(|(field, ty)| {
                    emath_exec_ir::constructor_emir::generic_type_signature(&ty, &objects, &params)
                        .map(|signature| (field, signature))
                })
                .collect::<Option<Vec<_>>>();
            if let Some(fields) = fields {
                templates.insert(
                    decl.name.clone(),
                    crate::codegen_render::RecordTemplate { params, fields },
                );
            }
        } else if decl.as_kind == "object" {
            let mut fields = Vec::new();
            let mut mappable = true;
            for (field, ty) in
                emath_exec_ir::constructor_emir::section_typed_fields(decl, "representation")
            {
                match emath_exec_ir::constructor_emir::constructor_type_signature(&ty, &objects) {
                    Some(signature) => fields.push((field, signature)),
                    None => mappable = false,
                }
            }
            if mappable {
                records.push(AuthoredRecord {
                    name: decl.name.clone(),
                    fields,
                });
            }
        } else if decl.as_kind == "function" {
            // Multi-output functions pack their outputs as a record
            // named after the function (the lowerer's output packing),
            // so the entry's result carrier needs that layout too.
            let outputs = emath_exec_ir::constructor_emir::section_typed_fields(decl, "outputs");
            if outputs.len() > 1 {
                let mut fields = Vec::new();
                let mut mappable = true;
                for (output, ty) in outputs {
                    match emath_exec_ir::constructor_emir::constructor_type_signature(
                        &ty, &objects,
                    ) {
                        Some(signature) => fields.push((output, signature)),
                        None => mappable = false,
                    }
                }
                if mappable {
                    records.push(AuthoredRecord {
                        name: decl.name.clone(),
                        fields,
                    });
                }
            }
        }
    }
    for record in &mut records {
        for (_, signature) in &mut record.fields {
            *signature = crate::codegen_render::stored_field_signature(signature);
        }
    }
    let _templates = crate::codegen_render::RecordTemplateScope::enter(templates);
    let _layouts = crate::codegen_render::AuthoredRecordScope::enter(
        records
            .iter()
            .map(|record| (record.name.clone(), record.fields.clone()))
            .collect(),
    );
    let mut rust = String::from(EMITTED_HEADER);
    let mut runnable = true;
    let mut unresolved = Vec::new();
    // The module callable table for the shared-tree lane (view's
    // Global layouts, dependency stamps): emitted as one crate-level
    // static when any lowered program carries the tree lane. The
    // stamps are the same FNV-1a `decl_stamp` digests the VM's quote
    // capture computes, so an artifact's stamped dependencies are
    // byte-identical to the VM's.
    let module_table = emath_exec_ir::constructor_layer::module_callable_table(&tree);
    let mut needs_module_table = false;
    let mut needs_definition_table = false;
    match emit_record_definitions(&records) {
        Ok(definitions) => rust.push_str(&definitions),
        Err(error) => {
            runnable = false;
            unresolved.push(error.to_string());
        }
    }
    // Lower every function once: the main file's functions, then every
    // sibling a lowered program names - recursion-cycle edges
    // (`CallSibling`, which need an entry) and inlined sibling frames
    // (named `CallFrame`s, which may call one) - to a fixed point.
    use std::collections::VecDeque;
    let mut lowered: BTreeMap<String, Result<emath_exec_ir::constructor_emir::LoweredFunction, String>> =
        BTreeMap::new();
    let mut session = emath_exec_ir::constructor_emir::ConstructorLowering::new(&tree);
    let mut queue: VecDeque<String> = functions.iter().cloned().collect();
    while let Some(name) = queue.pop_front() {
        if lowered.contains_key(&name) {
            continue;
        }
        let result = session.lower(&name);
        if let Ok(function) = &result
            && function.runnable
        {
            let mut named = Vec::new();
            collect_named_calls(&function.program, true, &mut named);
            queue.extend(named);
        }
        lowered.insert(name, result);
    }
    // The required entries: the main file's functions (authored order),
    // then every cycle member a required program references, settled to
    // a fixed point in discovery order. A required entry that cannot
    // emit makes the crate not runnable.
    let mut required: Vec<String> = functions.clone();
    let mut index = 0;
    while index < required.len() {
        if let Some(Ok(function)) = lowered.get(&required[index])
            && function.runnable
        {
            let mut siblings = Vec::new();
            collect_named_calls(&function.program, false, &mut siblings);
            for sibling in siblings {
                if !required.contains(&sibling) {
                    required.push(sibling);
                }
            }
        }
        index += 1;
    }
    // Run-time code reaches module functions no emitted program calls
    // (a formula handed in as a `Code` input may name any of them): when
    // any lowered program evaluates code, every data-ABI function of
    // the merged tree - imported ones included - joins as a helper root,
    // so the module table carries its adapter. Helpers never make the
    // crate not runnable; one that cannot emit is skipped.
    let evaluates_code = lowered.values().any(|function| {
        matches!(function, Ok(function) if function.runnable && contains_code_evaluate(&function.program))
    });
    let mut extra_roots: Vec<String> = Vec::new();
    if evaluates_code {
        for item in &tree.items {
            let emath_core::tree::Item::Declaration(decl) = item else {
                continue;
            };
            if decl.as_kind != "function"
                || lowered.contains_key(&decl.name)
                || !declared_node_abi(decl, &objects)
            {
                continue;
            }
            let result = session.lower(&decl.name);
            lowered.insert(decl.name.clone(), result);
            extra_roots.push(decl.name.clone());
        }
    }
    // The emitted entry's true result carrier per function,
    // pre-lowered once over every lowered function (imported cycle
    // members included) before any rendering: a `CallSibling`
    // register carries the callee's EMITTED carrier, and that is the
    // callee's inferred body join -
    // not the authored declaration - whenever the two disagree (a
    // Rat-typed inlined carrier joining an Int-declared recursive
    // tail emits the ratio carrier at the entry). The input kinds
    // mirror the entry ABI's declared carriers exactly.
    let mut sibling_kinds: BTreeMap<String, EntryAbi> = BTreeMap::new();
    let emitted_result = |name: &str, body_kind: ValueKind| {
        if matches!(
            body_kind,
            ValueKind::CodeValue | ValueKind::Evaluated | ValueKind::Cell
        ) || crate::codegen_render::kind_is_degenerate(&body_kind)
        {
            declared_output(&tree, name, &objects)
                .map(|(_, signature)| ValueKind::from_signature(signature.as_str()))
                .unwrap_or(body_kind)
        } else {
            body_kind
        }
    };
    for (name, lowered) in &lowered {
        if tree.items.iter().any(|item| matches!(item,
            emath_core::tree::Item::Declaration(decl)
                if decl.name == *name && !decl.generics.is_empty()))
        {
            continue;
        }
        let Ok(lowered) = lowered else {
            continue;
        };
        let mut kinds = InputKinds::new();
        let mut input_names = Vec::new();
        for (input, signature) in entry_inputs(&tree, name, &lowered.inputs, &objects) {
            kinds.insert(
                input.clone(),
                signature
                    .as_deref()
                    .map_or(ValueKind::I64, ValueKind::from_signature),
            );
            input_names.push(input);
        }
        crate::codegen_render::refine_recursive_frame_kinds(&lowered.program, &input_names, &[], &mut kinds);
        let body_kind = program_kind(&lowered.program, &input_names, &[], &kinds);
        // The entry ABI law, mirrored: a `CodeValue` body result
        // projects checked onto the declared scalar carrier at the
        // expression-template boundary (the entry emits the declared
        // carrier as its return type - `quote.evaluate`'s Int is an
        // Int at every caller, never the raw union). The sibling
        // table carries the EMITTED entry carrier, so a caller's
        // `CallSibling` register kind must match what the emitted
        // entry actually returns.
        let sibling_kind = emitted_result(name, body_kind);
        sibling_kinds.insert(name.clone(), EntryAbi {
            inputs: input_names.iter().map(|name| kinds[name].clone()).collect(),
            result: sibling_kind,
        });
    }
    // A cycle's widened inputs can widen its result and then a caller's
    // inputs. Settle both sides before rendering any member.
    for _ in 0..sibling_kinds.len() {
        let scope = SiblingEntryScope::enter(sibling_kinds.clone());
        let (results, passed) = crate::codegen_render::with_sibling_call_scope(|| {
            let mut results = Vec::new();
            for (name, lowered) in &lowered {
                let (Ok(lowered), Some(abi)) = (lowered, sibling_kinds.get(name)) else {
                    continue;
                };
                let names = lowered.inputs.clone();
                let frame = names
                    .iter()
                    .cloned()
                    .zip(abi.inputs.iter().cloned())
                    .collect();
                let body_kind = program_kind(&lowered.program, &names, &[], &frame);
                results.push((name.clone(), emitted_result(name, body_kind)));
            }
            results
        });
        drop(scope);
        let mut changed = false;
        for (name, result) in results {
            if let Some(abi) = sibling_kinds.get_mut(&name) {
                changed |= result != abi.result;
                abi.result = result;
            }
        }
        for (name, passed) in passed {
            if let Some(abi) = sibling_kinds.get_mut(&name) {
                for (kind, passed) in abi.inputs.iter_mut().zip(passed) {
                    let widened = crate::codegen_render::widen_name_carrier(kind, &passed);
                    changed |= widened != *kind;
                    *kind = widened;
                }
            }
        }
        if !changed {
            break;
        }
    }
    let _sibling_scope = SiblingEntryScope::enter(sibling_kinds);
    // Entries render callees-first (post-order over the named-call
    // graph, cycles cut at the open ancestor) so every entry's ABI is
    // registered before a caller renders: a caller's named frame whose
    // carriers equal the callee's ABI becomes a call to that entry
    // instead of the callee's body inlined again at every site (the
    // multiplicative blowup of nested sibling calls). Helpers - named
    // callees outside the required set, imported ones included - emit
    // only to serve those calls: a helper that cannot emit or names a
    // cycle member without an entry is skipped and its callers keep
    // inlining. Tree-lane functions (named up front, so cycle edges
    // rendered before their target emits agree) are called through
    // their non-resetting body fn.
    let callees_of = |name: &str| -> Vec<String> {
        let mut named = Vec::new();
        if let Some(Ok(function)) = lowered.get(name)
            && function.runnable
        {
            collect_named_calls(&function.program, true, &mut named);
        }
        named.reverse();
        named
    };
    let mut post_order: Vec<String> = Vec::new();
    let mut visited: BTreeSet<String> = BTreeSet::new();
    for root in required.iter().chain(&extra_roots) {
        if !visited.insert(root.clone()) {
            continue;
        }
        let mut stack: Vec<(String, Vec<String>)> = vec![(root.clone(), callees_of(root))];
        loop {
            let Some(top) = stack.last_mut() else {
                break;
            };
            match top.1.pop() {
                Some(next) => {
                    if visited.insert(next.clone()) {
                        let callees = callees_of(&next);
                        stack.push((next, callees));
                    }
                }
                None => {
                    if let Some((name, _)) = stack.pop() {
                        post_order.push(name);
                    }
                }
            }
        }
    }
    let tree_lane: BTreeSet<String> = lowered
        .iter()
        .filter_map(|(name, function)| match function {
            Ok(function) if crate::contains_tree_ops(&function.program) => Some(name.clone()),
            _ => None,
        })
        .collect();
    let _entry_scope = EntryAbiScope::enter(tree_lane);
    // Text and refusals collect per function and assemble in the
    // required order (main file first, cycle members as discovered),
    // helpers last - the render order is an implementation detail.
    // A function with type parameters has no single carrier ABI: it
    // emits no entry, and every call site inlines its body as a frame
    // typed by that site's arguments (one instantiation per call site).
    let generic: BTreeSet<String> = tree
        .items
        .iter()
        .filter_map(|item| match item {
            emath_core::tree::Item::Declaration(decl) if !decl.generics.is_empty() => {
                Some(decl.name.clone())
            }
            _ => None,
        })
        .collect();
    // Generic cycle members: a `CallSibling` edge names a callee with
    // type parameters, which has no single-carrier entry of its own.
    // Each call site instantiates the callee - the site's argument
    // carriers are the instantiation - so the emitter monomorphizes
    // ONE concrete entry per member (under the plain mangled name,
    // which is what every site already calls) when exactly one
    // instantiation exists. A member with no sites, with conflicting
    // instantiations, or with an unresolvable type parameter renders
    // no entry, and the calling function refuses by name at its
    // `CallSibling` - the crate NEVER calls a missing entry (bead
    // emath-qhl1i).
    //
    // The site walk replays the render's own kind laws (kind_of_op via
    // value_kinds, frame bindings from argument carriers) without
    // rendering: the render re-derives everything it needs, so a
    // mis-collected binding can only fail to compile, never produce a
    // wrong-but-compiling artifact.
    let mut instantiations: BTreeMap<String, (BTreeMap<String, String>, bool)> = BTreeMap::new();
    {
        use crate::codegen_render;
        fn merge_site(
            callee: &str,
            bound: &BTreeMap<String, String>,
            out: &mut BTreeMap<String, (BTreeMap<String, String>, bool)>,
        ) {
            for (var, concrete) in bound {
                let member = out.entry(callee.to_string()).or_default();
                match member.0.get(var) {
                    Some(existing) if existing != concrete => member.1 = true,
                    _ => {
                        member.0.insert(var.clone(), concrete.clone());
                    }
                }
            }
        }
        fn walk_generic_sites(
            program: &emath_exec_ir::EmirProgram,
            kinds: &[ValueKind],
            input_kinds: &InputKinds,
            names: &[String],
            states: &[String],
            prefix: &BTreeMap<String, String>,
            generic: &BTreeSet<String>,
            out: &mut BTreeMap<String, (BTreeMap<String, String>, bool)>,
        ) {
            use crate::codegen_render;
            use emath_exec_ir::EmirOp;
            let kind_of = |value: emath_exec_ir::EmirValue| -> ValueKind {
                kinds.get(value.0 as usize).cloned().unwrap_or(ValueKind::Other)
            };
            for (op, _) in &program.ops {
                match op {
                    EmirOp::CallSibling { name, inputs, declared, .. }
                        if generic.contains(name) =>
                    {
                        let mut bound = prefix.clone();
                        for (signature, value) in declared.iter().zip(inputs) {
                            codegen_render::bind_signature_vars(
                                signature,
                                &kind_of(*value),
                                &mut bound,
                            );
                        }
                        merge_site(name, &bound, out);
                    }
                    EmirOp::CallFrame { body, inputs, declared, bindings, .. } => {
                        // The frame's carriers: the render's law - the
                        // frame's declared signatures bind from the
                        // site's argument kinds (plus the enclosing
                        // frames' bindings), and the body walks with
                        // its own register space.
                        let mut frame_bound = prefix.clone();
                        frame_bound.extend(bindings.iter().cloned());
                        for (signature, value) in declared.iter().zip(inputs) {
                            codegen_render::bind_signature_vars(
                                signature,
                                &kind_of(*value),
                                &mut frame_bound,
                            );
                        }
                        let frame_names: Vec<String> = (0..usize::from(body.input_count))
                            .map(|index| format!("__frame_input_{index}"))
                            .collect();
                        let mut frame_input_kinds = InputKinds::new();
                        for (name, signature) in frame_names.iter().zip(declared) {
                            frame_input_kinds.insert(
                                name.clone(),
                                ValueKind::from_signature(&codegen_render::substitute_signature_vars(
                                    signature, &frame_bound,
                                )),
                            );
                        }
                        let body_kinds = codegen_render::value_kinds(
                            body,
                            &frame_names,
                            &[],
                            &frame_input_kinds,
                        );
                        walk_generic_sites(
                            body,
                            &body_kinds,
                            &frame_input_kinds,
                            &frame_names,
                            &[],
                            &frame_bound,
                            generic,
                            out,
                        );
                    }
                    EmirOp::Branch {
                        then_body, else_body, ..
                    } => {
                        for body in [then_body, else_body] {
                            let body_kinds =
                                codegen_render::value_kinds(body, names, states, input_kinds);
                            walk_generic_sites(
                                body, &body_kinds, input_kinds, names, states, prefix, generic,
                                out,
                            );
                        }
                    }
                    EmirOp::ProgramLiteral { body, .. }
                    | EmirOp::Fold { body, .. }
                    | EmirOp::Collect { body, .. } => {
                        let body_kinds =
                            codegen_render::value_kinds(body, names, states, input_kinds);
                        walk_generic_sites(
                            body, &body_kinds, input_kinds, names, states, prefix, generic, out,
                        );
                    }
                    EmirOp::Iterate { body, stop, .. } => {
                        let body_kinds =
                            codegen_render::value_kinds(body, names, states, input_kinds);
                        walk_generic_sites(
                            body, &body_kinds, input_kinds, names, states, prefix, generic, out,
                        );
                        if let Some(stop) = stop {
                            let stop_kinds =
                                codegen_render::value_kinds(stop, names, states, input_kinds);
                            walk_generic_sites(
                                stop, &stop_kinds, input_kinds, names, states, prefix, generic,
                                out,
                            );
                        }
                    }
                    _ => {}
                }
            }
        }
        for root in required.iter().chain(&extra_roots) {
            let Some(Ok(function)) = lowered.get(root) else {
                continue;
            };
            if !function.runnable {
                continue;
            }
            let mut kinds = InputKinds::new();
            let mut input_names = Vec::new();
            for (input, signature) in entry_inputs(&tree, root, &function.inputs, &objects) {
                kinds.insert(
                    input.clone(),
                    signature
                        .as_deref()
                        .map_or(ValueKind::I64, ValueKind::from_signature),
                );
                input_names.push(input);
            }
            crate::codegen_render::refine_recursive_frame_kinds(
                &function.program,
                &input_names,
                &[],
                &mut kinds,
            );
            let program_kinds = codegen_render::value_kinds(
                &function.program,
                &input_names,
                &[],
                &kinds,
            );
            walk_generic_sites(
                &function.program,
                &program_kinds,
                &kinds,
                &input_names,
                &[],
                &BTreeMap::new(),
                &generic,
                &mut instantiations,
            );
        }
    }
    let mut rendered: BTreeMap<String, String> = BTreeMap::new();
    let mut refusals: BTreeMap<String, Vec<String>> = BTreeMap::new();
    let mut helpers: Vec<String> = Vec::new();
    let mut emitted_entries: Vec<(String, Vec<(String, Option<String>)>, EntryAbi)> = Vec::new();
    for name in &post_order {
        if generic.contains(name) {
            let stub = || {
                format!("// function `{name}` has type parameters: each call site inlines it\n")
            };
            let Some(Ok(function)) = lowered.get(name) else {
                rendered.insert(name.clone(), stub());
                continue;
            };
            if !function.runnable {
                rendered.insert(name.clone(), stub());
                continue;
            }
            // Monomorphize the cycle member: exactly one call-site
            // instantiation (no conflicts) renders a concrete entry
            // under the plain mangled name every site already calls.
            let Some((bindings, false)) = &instantiations.get(name) else {
                rendered.insert(name.clone(), stub());
                continue;
            };
            if bindings.is_empty() {
                rendered.insert(name.clone(), stub());
                continue;
            }
            // The member's authored input signatures with the site's
            // instantiation substituted: `Receipt<S>` under
            // `S = Vector<ExactInt>` re-resolves where the raw
            // generic text refused to map (`constructor_type_signature`
            // declines a type parameter), and the entry's input kinds
            // follow the concrete carriers, not the I64 fallback.
            let authored_inputs: Vec<(String, Option<String>)> = tree
                .items
                .iter()
                .find_map(|item| match item {
                    emath_core::tree::Item::Declaration(decl) if decl.name == *name => {
                        let vars: Vec<String> =
                            decl.generics.iter().map(|generic| generic.name.clone()).collect();
                        Some(
                            emath_exec_ir::constructor_emir::section_typed_fields(decl, "inputs")
                                .into_iter()
                                .map(|(input, ty)| {
                                    (
                                        input,
                                        emath_exec_ir::constructor_emir::generic_type_signature(
                                            &ty, &objects, &vars,
                                        ),
                                    )
                                })
                                .collect(),
                        )
                    }
                    _ => None,
                })
                .unwrap_or_default();
            let bound_inputs: Vec<(String, Option<String>)> = entry_inputs(
                &tree,
                name,
                &function.inputs,
                &objects,
            )
            .into_iter()
            .map(|(input, signature)| {
                let signature = signature.or_else(|| {
                    authored_inputs
                        .iter()
                        .find(|(declared, _)| declared == &input)
                        .and_then(|(_, text)| text.as_ref())
                        .map(|text| substitute_signature_vars(text, bindings))
                });
                (input, signature)
            })
            .collect();
            let bound_output = declared_output(&tree, name, &objects)
                .map(|(output, signature)| (output, substitute_signature_vars(&signature, bindings)));
            let bindings_scope = crate::codegen_render::TypeBindingScope::enter_bound(
                &bindings
                    .iter()
                    .map(|(name, carrier)| (name.clone(), carrier.clone()))
                    .collect::<Vec<_>>(),
            );
            let mut kinds = InputKinds::new();
            let mut input_names = Vec::new();
            for (input, signature) in &bound_inputs {
                kinds.insert(
                    input.clone(),
                    signature
                        .as_deref()
                        .map_or(ValueKind::I64, ValueKind::from_signature),
                );
                input_names.push(input.clone());
            }
            crate::codegen_render::refine_recursive_frame_kinds(
                &function.program,
                &input_names,
                &[],
                &mut kinds,
            );
            needs_module_table |= crate::contains_tree_ops(&function.program);
            needs_definition_table |= crate::contains_body_ops(&function.program);
            let previous_rendering =
                crate::codegen_render::set_rendering_generic_member(Some(name.clone()));
            let emitted =
                emit_constructor_entry_abi(
                    &function.program,
                    name,
                    &bound_inputs,
                    bound_output
                        .as_ref()
                        .map(|(output, signature)| (output.as_str(), signature.as_str())),
                    &records,
                );
            crate::codegen_render::set_rendering_generic_member(previous_rendering);
            match emitted {
                Ok((body, abi)) => {
                    emitted_entries.push((name.clone(), bound_inputs.clone(), abi.clone()));
                    register_entry_abi(name, abi);
                    rendered.insert(name.clone(), format!("// function `{name}`\n{body}\n"));
                }
                Err(error) => {
                    runnable = false;
                    refusals.insert(name.clone(), vec![error.to_string()]);
                    rendered.insert(
                        name.clone(),
                        format!("// `{name}` is not marked runnable: {error}\n"),
                    );
                }
            }
            drop(bindings_scope);
            continue;
        }
        let is_required = required.contains(name);
        let function = match lowered.get(name) {
            Some(Ok(function)) => function,
            Some(Err(error)) => {
                if is_required {
                    runnable = false;
                    refusals.insert(name.clone(), vec![error.clone()]);
                }
                continue;
            }
            None => continue,
        };
        if !function.runnable {
            if is_required {
                runnable = false;
                refusals.insert(name.clone(), function.unresolved.clone());
                rendered.insert(
                    name.clone(),
                    format!("// `{name}` is not marked runnable: unresolved symbolic code\n"),
                );
            }
            continue;
        }
        if is_required {
            needs_module_table |= crate::contains_tree_ops(&function.program);
            needs_definition_table |= crate::contains_body_ops(&function.program);
        } else {
            let mut siblings = Vec::new();
            collect_named_calls(&function.program, false, &mut siblings);
            if siblings
                .iter()
                .any(|sibling| sibling != name && entry_abi(sibling).is_none())
            {
                continue;
            }
        }
        // Declared carriers ground the entry ABI; an untyped input
        // falls back to the numeric lane's Int. The merged tree
        // resolves imported functions too. The single-output
        // declaration is the carrier authority at the
        // expression-template boundary (the checked projection site);
        // multi-output functions pack a record and never carry a raw
        // union result.
        let inputs = entry_inputs(&tree, name, &function.inputs, &objects);
        let output = declared_output(&tree, name, &objects);
        match emit_constructor_entry_abi(
            &function.program,
            name,
            &inputs,
            output
                .as_ref()
                .map(|(output, signature)| (output.as_str(), signature.as_str())),
            &records,
        ) {
            Ok((body, abi)) => {
                emitted_entries.push((name.clone(), inputs.clone(), abi.clone()));
                register_entry_abi(name, abi);
                if !is_required {
                    needs_module_table |= crate::contains_tree_ops(&function.program);
                    needs_definition_table |= crate::contains_body_ops(&function.program);
                    helpers.push(name.clone());
                }
                rendered.insert(name.clone(), format!("// function `{name}`\n{body}\n"));
            }
            Err(error) => {
                if is_required {
                    runnable = false;
                    refusals.insert(name.clone(), vec![error.to_string()]);
                    rendered.insert(
                        name.clone(),
                        format!("// `{name}` is not marked runnable: {error}\n"),
                    );
                }
            }
        }
    }
    emit_exact_twins(&post_order, &lowered, &emitted_entries, &tree, &objects, &records, &mut rendered);
    for name in required.iter().chain(&helpers) {
        if let Some(text) = rendered.get(name) {
            rust.push_str(text);
        }
        if let Some(refused) = refusals.remove(name) {
            unresolved.extend(refused);
        }
    }
    // Generic objects emit one struct per instantiation the rendered
    // entries resolved; a struct's own fields may name further
    // instantiations, so this runs to a fixed point. Rendering that
    // follows the entries (the callable adapters over entry ABIs,
    // the distilled definition table) resolves further instantiations,
    // so the pass repeats after the tables assemble too.
    let mut instantiated: BTreeSet<String> = BTreeSet::new();
    let emit_instantiated = |rust: &mut String,
                                 records: &mut Vec<AuthoredRecord>,
                                 instantiated: &mut BTreeSet<String>,
                                 runnable: &mut bool,
                                 unresolved: &mut Vec<String>| {
        loop {
            let drained = crate::codegen_render::take_instantiations();
            let fresh: Vec<AuthoredRecord> = drained
                .into_iter()
                .filter(|(name, _)| instantiated.insert(name.clone()))
                .map(|(name, fields)| AuthoredRecord { name, fields })
                .collect();
            if fresh.is_empty() {
                break;
            }
            for record in &fresh {
                for (_, signature) in &record.fields {
                    crate::codegen_render::touch_record_kinds(signature);
                }
            }
            match emit_record_definitions(&fresh) {
                Ok(definitions) => rust.push_str(&definitions),
                Err(error) => {
                    *runnable = false;
                    unresolved.push(error.to_string());
                }
            }
            records.extend(fresh);
        }
    };
    emit_instantiated(
        &mut rust,
        &mut records,
        &mut instantiated,
        &mut runnable,
        &mut unresolved,
    );
    // A union-lane executor (`evaluate`/`evaluate_callable` over a Code
    // input) reads the table without carrying the tree lane.
    if needs_module_table || rust.contains("&__EMATH_MODULE_TABLE") {
        // The tree evaluator's route into module code: one adapter per
        // emitted entry whose ABI crosses as scalars (a run-time
        // formula calling a module function runs its compiled entry).
        let mut callables = Vec::new();
        let mut node_callables = Vec::new();
        for (name, inputs, abi) in &emitted_entries {
            if let Some(adapter) = scalar_entry_adapter(name, inputs, abi) {
                rust.push_str(&adapter);
                callables.push(format!("({name:?}, emath_callable_{name})"));
            }
            if let Some(adapter) = node_entry_adapter(name, inputs, abi) {
                rust.push_str(&adapter);
                node_callables.push(format!("({name:?}, emath_node_callable_{name})"));
            }
        }
        let callables = callables.join(", ");
        let node_callables = node_callables.join(", ");
        let globals = module_table
            .iter()
            .map(|(name, opaque, _)| format!("({name:?}, {opaque})"))
            .collect::<Vec<_>>()
            .join(", ");
        let stamps = module_table
            .iter()
            .map(|(name, _, stamp)| format!("({name:?}, {stamp})"))
            .collect::<Vec<_>>()
            .join(", ");
        rust.push_str(&format!(
            "#[allow(dead_code)]\nstatic __EMATH_MODULE_TABLE: emath_rt::code_tree::ModuleTable = emath_rt::code_tree::ModuleTable {{ globals: &[{globals}], stamps: &[{stamps}], callables: &[{callables}], node_callables: &[{node_callables}] }};\n\n"
        ));
    }
    // The definition table: the
    // module's function bodies as DATA - the same bodies the
    // compiled entries come from, distilled by the same lowering, so
    // a `quote.body` unfold and a compiled call cannot disagree (the
    // dual-representation law). Built once at first use; a
    // transparent body outside the distilled subset stays `None` and
    // the runtime unfold refuses by name.
    if needs_definition_table {
        let rows = emath_exec_ir::constructor_layer::module_definition_table(&tree);
        let rows = rows
            .iter()
            .map(|(name, opaque, body)| {
                let body = match body {
                    Some(tree) => format!("Some({})", crate::codegen_render::tree_expr(tree)),
                    None => "None".to_string(),
                };
                format!(
                    "emath_rt::code_tree::DefinitionRow {{ name: String::from({name:?}), opaque: {opaque}, body: {body} }}"
                )
            })
            .collect::<Vec<_>>()
            .join(", ");
        rust.push_str(&format!(
            "#[allow(dead_code)]\nstatic __EMATH_DEFINITIONS: std::sync::LazyLock<emath_rt::code_tree::DefinitionTable> = std::sync::LazyLock::new(|| emath_rt::code_tree::DefinitionTable {{ rows: vec![{rows}] }});\n\n"
        ));
    }
    emit_instantiated(
        &mut rust,
        &mut records,
        &mut instantiated,
        &mut runnable,
        &mut unresolved,
    );
    // A function using `quote.cost`/`quote.world`/`quote.worlds` runs in
    // the reference engine, which reads the module source: the crate
    // embeds it, every module its `use` imports resolve to (so the
    // artifact never reads them from disk), and the world list
    // `quote.worlds()` returns (the host's at build time).
    let mut engine_dependency = if rust.contains("artifact_bridge::run_entry") {
        // Resolve relative keys without following symlinks or rereading sources:
        // the root, search roots and retained files must keep one path policy.
        let absolute = |path: &Path| {
            std::path::absolute(path).map_err(|error| ConstructorEmitRefusal::ImportsRefused {
                e_code: "E-USE-ADMISSION".into(),
                detail: format!(
                    "cannot retain absolute import path {}: {error}",
                    path.display()
                ),
            })
        };
        let path = absolute(spec_path)?;
        let (roots, modules) = module.import_files();
                let roots = roots
                    .iter()
                    .map(|root| {
                        absolute(root).map(|path| format!("{:?}", path.display().to_string()))
                    })
                    .collect::<Result<Vec<_>, _>>()?
                    .join(", ");
                let modules = modules
                    .iter()
                    .map(|(file, text)| {
                        absolute(file).map(|path| format!("({:?}, {text:?})", path.display().to_string()))
                    })
                    .collect::<Result<Vec<_>, _>>()?
                    .join(", ");
                rust.push_str(&format!(
                    "static __EMATH_MODULE_ROOTS: &[&str] = &[{roots}];\nstatic __EMATH_MODULES: &[(&str, &str)] = &[{modules}];\n"
                ));
                let worlds = emath_exec_ir::constructor_layer::configured_worlds()
                    .iter()
                    .map(|world| format!("{:?}", world.name()))
                    .collect::<Vec<_>>()
                    .join(", ");
                rust.push_str(&format!(
                    "static __EMATH_SOURCE: &str = {source:?};\nstatic __EMATH_SOURCE_PATH: &str = {:?};\nstatic __EMATH_WORLDS: &[&str] = &[{worlds}];\n\n",
                    path.display().to_string()
                ));
                // Authored objects cross the engine boundary through
                // the bridge traits, implemented here for every record
                // struct whose fields all cross.
                const BRIDGE: &str = "emath_exec_ir::constructor_layer::artifact_bridge";
                let _layouts = crate::codegen_render::AuthoredRecordScope::enter(
                    records
                        .iter()
                        .map(|record| (record.name.clone(), record.fields.clone()))
                        .collect(),
                );
                for record in &records {
                    let kind = ValueKind::Record(record.name.clone());
                    if !crate::codegen_render::engine_crosses(&kind) {
                        continue;
                    }
                    let ident = crate::codegen_render::record_ident(&record.name);
                    let to_fields = record
                        .fields
                        .iter()
                        .map(|(field, _)| {
                            format!(
                                "({field:?}, {BRIDGE}::ToCValue::to_cvalue(&self.{}))",
                                crate::rust_ir::ast::escape_ident(field)
                            )
                        })
                        .collect::<Vec<_>>()
                        .join(", ");
                    let from_fields = record
                        .fields
                        .iter()
                        .map(|(field, _)| {
                            format!(
                                "{}: {BRIDGE}::field(value, {field:?})?",
                                crate::rust_ir::ast::escape_ident(field)
                            )
                        })
                        .collect::<Vec<_>>()
                        .join(", ");
                    rust.push_str(&format!(
                        "impl {BRIDGE}::ToCValue for EmathRecord_{ident} {{\n    fn to_cvalue(&self) -> emath_exec_ir::constructor_layer::CValue {{\n        {BRIDGE}::record({:?}, vec![{to_fields}])\n    }}\n}}\n\nimpl {BRIDGE}::FromCValue for EmathRecord_{ident} {{\n    fn from_cvalue(value: &emath_exec_ir::constructor_layer::CValue) -> Result<Self, String> {{\n        Ok(EmathRecord_{ident} {{ {from_fields} }})\n    }}\n}}\n\n",
                        record.name
                    ));
                }
        "emath-exec-ir = { path = \"vendor/emath-exec-ir\" }\n".to_string()
    } else {
        String::new()
    };
    let links_engine = !engine_dependency.is_empty();
    if links_engine && rust.contains("emath_rt::") {
        // The vendored engine already carries the runtime as a crate
        // with the same API; embedding a second copy would compile it
        // twice and make its types distinct from the engine's.
        engine_dependency.push_str("emath-rt = { path = \"vendor/emath-rt\" }\n");
        rust.insert_str(EMITTED_HEADER.len(), "pub use emath_rt;\n\n");
    } else if rust.contains("emath_rt::") {
        // Self-containment law (emath-rt's `SOURCE` embed, the same
        // law the SIR lane followed): the runtime ships inside the
        // artifact as `mod emath_rt`, so the emitted crate builds
        // with zero external dependencies.
        rust.insert_str(
            EMITTED_HEADER.len(),
            &format!(
                "#[allow(dead_code)]\npub mod emath_rt {{\n{}\n}}\n\n",
                emath_rt::SOURCE
            ),
        );
    }
    // A buildable crate needs its manifest; the runtime is embedded,
    // so the dependency list stays empty (unless a function runs in the
    // reference engine) and the artifact compiles offline.
    let stem = spec_path
        .file_stem()
        .and_then(|stem| stem.to_str())
        .unwrap_or("emath_build");
    let mut package_name: String = stem
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() || c == '_' || c == '-' { c } else { '_' })
        .collect();
    if package_name.is_empty() || package_name.starts_with(|c: char| c.is_ascii_digit()) {
        package_name = format!("emath_{package_name}");
    }
    let manifest = format!(
        "# Generated by `emath build`; {}.\n[package]\nname = \"{package_name}\"\nversion = \"0.1.0\"\nedition = \"2024\"\n\n[workspace]\n\n[dependencies]\n{engine_dependency}",
        if links_engine {
            "functions using quote.cost/world/worlds run in the\n# reference engine, vendored with the runtime under vendor/"
        } else {
            "the emath runtime is embedded\n# as `mod emath_rt` in src/lib.rs - no dependencies"
        }
    );
    Ok(ConstructorCrateEmission {
        lib: rust,
        manifest,
        package_name,
        runnable,
        functions,
        unresolved,
        records,
        links_engine,
    })
}

/// Whether a program evaluates quoted code at any depth (the run-time
/// lane that can call module functions through the table).
fn contains_code_evaluate(program: &emath_exec_ir::EmirProgram) -> bool {
    use emath_exec_ir::EmirOp;
    program.ops.iter().any(|(op, _)| match op {
        EmirOp::CodeEvaluate { .. } => true,
        EmirOp::Branch {
            then_body,
            else_body,
            ..
        } => contains_code_evaluate(then_body) || contains_code_evaluate(else_body),
        EmirOp::CallFrame { body, .. }
        | EmirOp::ProgramLiteral { body, .. }
        | EmirOp::Fold { body, .. }
        | EmirOp::Collect { body, .. } => contains_code_evaluate(body),
        EmirOp::Iterate { body, stop, .. } => {
            contains_code_evaluate(body) || stop.as_ref().is_some_and(contains_code_evaluate)
        }
        _ => false,
    })
}

/// Whether a function declares data carriers that a node-callable adapter
/// can cross. Callable parameters themselves are not data nodes.
fn declared_node_abi(
    decl: &emath_core::tree::Declaration,
    objects: &std::collections::BTreeSet<String>,
) -> bool {
    let node = |ty: &emath_core::tree::TypeExpr| {
        emath_exec_ir::constructor_emir::constructor_type_signature(ty, objects)
            .is_some_and(|signature| crate::codegen_render::node_family(
                &ValueKind::from_signature(&signature),
            ))
    };
    let outputs = emath_exec_ir::constructor_emir::section_typed_fields(decl, "outputs");
    outputs.len() == 1
        && node(&outputs[0].1)
        && emath_exec_ir::constructor_emir::section_typed_fields(decl, "inputs")
            .iter()
            .all(|(_, ty)| node(ty))
}

/// A module function's compiled entry adapted to the scalar union for
/// the tree evaluator (`ModuleTable::callables`): each argument projects
/// checked onto the declared Int/Rat/Bool parameter (the slot names the
/// parameter), the result wraps back into the union. A tree-lane entry
/// is called through its body fn, so a run's mint continues. Entries
/// with any non-scalar parameter or result get no adapter - a run-time
/// call to them refuses by name in the evaluator.
fn scalar_entry_adapter(
    name: &str,
    inputs: &[(String, Option<String>)],
    abi: &EntryAbi,
) -> Option<String> {
    let project = |kind: &ValueKind| match kind {
        ValueKind::I64 | ValueKind::ExactInt => Some("project_i64"),
        ValueKind::Rational => Some("project_ratio"),
        ValueKind::Bool => Some("project_bool"),
        _ => None,
    };
    if !matches!(
        abi.result,
        ValueKind::I64 | ValueKind::ExactInt | ValueKind::Rational | ValueKind::Bool
    ) {
        return None;
    }
    if abi.inputs.len() != inputs.len() {
        return None;
    }
    let args = abi
        .inputs
        .iter()
        .zip(inputs)
        .enumerate()
        .map(|(index, (kind, (param, _)))| {
            let argument = format!(
                "emath_rt::code::{}(&__args[{index}], {param:?})?",
                project(kind)?
            );
            Some(if *kind == ValueKind::ExactInt {
                format!("emath_rt::ExactInt::from({argument})")
            } else {
                argument
            })
        })
        .collect::<Option<Vec<_>>>()?;
    let arity = abi.inputs.len();
    let target = internal_entry_name(name);
    let value = crate::codegen_render::to_code_value(
        crate::rust_ir::ast::Expr::Raw(format!("crate::{target}({})?", args.join(", "))),
        &abi.result,
    )
    .ok()?;
    let value = crate::rust_ir::render::render_expr(&value);
    Some(format!(
        "#[allow(dead_code)]\nfn emath_callable_{name}(__args: &[emath_rt::code::CodeValue]) -> Result<emath_rt::code::CodeValue, String> {{\n    if __args.len() != {arity} {{\n        return Err(format!(\"type: `{name}` expects {arity} argument(s), got {{}}\", __args.len()));\n    }}\n    Ok({value})\n}}\n\n"
    ))
}

fn node_entry_adapter(
    name: &str,
    inputs: &[(String, Option<String>)],
    abi: &EntryAbi,
) -> Option<String> {
    if abi.inputs.len() != inputs.len() {
        return None;
    }
    let mut bindings = Vec::new();
    let mut arguments = Vec::new();
    for (index, kind) in abi.inputs.iter().enumerate() {
        let argument = format!("__node_argument_{index}");
        let value = crate::codegen_render::node_into(&format!("__args[{index}]"), kind)?;
        bindings.push(format!("let {argument} = {value};"));
        arguments.push(argument);
    }
    let value = crate::codegen_render::to_node(
        crate::rust_ir::ast::Expr::Raw("__node_result".into()), &abi.result,
    ).ok()?;
    let value = crate::rust_ir::render::render_expr(&value);
    let target = internal_entry_name(name);
    let arity = abi.inputs.len();
    Some(format!(
        "#[allow(dead_code)]\nfn emath_node_callable_{name}(__args: &[emath_rt::code_tree::NodeValue]) -> Result<emath_rt::code_tree::NodeValue, String> {{\n    if __args.len() != {arity} {{ return Err(format!(\"type: `{name}` expects {arity} argument(s), got {{}}\", __args.len())); }}\n    {}\n    let __node_result = crate::{target}({})?;\n    Ok({value})\n}}\n\n",
        bindings.join("\n    "), arguments.join(", "),
    ))
}

type Lowered = BTreeMap<String, Result<emath_exec_ir::constructor_emir::LoweredFunction, String>>;

/// The i64 lane's exact fallback. An entry whose i64 body can refuse with
/// [`INT_LANE_FAULT`] gets a private twin rendered over `ExactInt`
/// carriers, and its public entry re-runs the twin on that fault. The VM's
/// Int is exact, so the twin computes the VM's answer; the public entry
/// narrows it onto the declared i64 carrier and returns the same fault only
/// when the answer itself does not fit. Only bodies of scalar, sequence,
/// branch and call ops qualify. A twin that does not render, or whose ABI
/// drifts from its table row, is dropped and the pass re-runs without it.
fn emit_exact_twins(
    post_order: &[String],
    lowered: &Lowered,
    emitted_entries: &[(String, Vec<(String, Option<String>)>, EntryAbi)],
    tree: &SyntaxTree,
    objects: &BTreeSet<String>,
    records: &[AuthoredRecord],
    rendered: &mut BTreeMap<String, String>,
) {
    let fast: BTreeMap<&str, (&[(String, Option<String>)], &EntryAbi)> = emitted_entries
        .iter()
        .map(|(name, inputs, abi)| (name.as_str(), (inputs.as_slice(), abi)))
        .collect();
    let program_of = |name: &str| match lowered.get(name) {
        Some(Ok(function)) => Some(&function.program),
        _ => None,
    };
    let mut twins: BTreeSet<String> = BTreeSet::new();
    for name in post_order {
        let (Some((_, abi)), Some(program), Some(text)) =
            (fast.get(name.as_str()), program_of(name), rendered.get(name))
        else {
            continue;
        };
        let mut callees = Vec::new();
        collect_named_calls(program, true, &mut callees);
        let faults = text.contains(INT_LANE_FAULT) || callees.iter().any(|callee| twins.contains(callee));
        if faults
            && exact_abi(abi).is_some()
            && exact_body(program)
            && text.contains(&fast_entry_head(name))
        {
            twins.insert(name.clone());
        }
    }
    loop {
        if twins.is_empty() {
            return;
        }
        let _pass = ExactTwinScope::enter(twins.clone());
        let mut table: BTreeMap<String, EntryAbi> = twins
            .iter()
            .filter_map(|name| Some((name.clone(), exact_abi(fast[name.as_str()].1)?)))
            .collect();
        let input_names = |name: &str| -> Vec<String> {
            fast[name].0.iter().map(|(input, _)| input.clone()).collect()
        };
        // Twin results feed callers' kinds: settle them as the fast pass does.
        let mut unsettled = None;
        for _ in 0..=table.len() {
            let _scope = SiblingEntryScope::enter(table.clone());
            let mut changed = false;
            for name in &twins {
                let names = input_names(name);
                let frame = names.iter().cloned().zip(table[name].inputs.iter().cloned()).collect();
                let result = program_kind(program_of(name).expect("twin is lowered"), &names, &[], &frame);
                if exact_kind(&result).is_none() {
                    unsettled = Some(name.clone());
                    break;
                }
                let row = table.get_mut(name).expect("twin has a row");
                changed |= row.result != result;
                row.result = result;
            }
            if unsettled.is_some() || !changed {
                break;
            }
        }
        if let Some(name) = unsettled {
            twins.remove(&name);
            continue;
        }
        let _scope = SiblingEntryScope::enter(table.clone());
        let _entries = EntryAbiScope::enter(BTreeSet::new());
        let mut texts = Vec::new();
        let mut failed = None;
        for name in post_order.iter().filter(|name| twins.contains(*name)) {
            let output = declared_output(tree, name, objects);
            let output = output.as_ref().map(|(output, signature)| (output.as_str(), signature.as_str()));
            match emit_constructor_entry_abi(
                program_of(name).expect("twin is lowered"),
                name,
                fast[name.as_str()].0,
                output,
                records,
            ) {
                Ok((text, abi)) if abi == table[name] => {
                    register_entry_abi(name, abi);
                    texts.push((name.clone(), text));
                }
                _ => {
                    failed = Some(name.clone());
                    break;
                }
            }
        }
        if let Some(name) = failed {
            twins.remove(&name);
            continue;
        }
        let entries: Vec<_> = texts
            .into_iter()
            .filter_map(|(name, twin)| {
                let (inputs, abi) = fast[name.as_str()];
                Some((name.clone(), twin, exact_entry(&name, inputs, abi, &table[&name])?))
            })
            .collect();
        for (name, twin, entry) in entries {
            if let Some(text) = rendered.get_mut(&name) {
                *text = text.replacen(&fast_entry_head(&name), &format!("fn emath_fast_{name}("), 1);
                text.push_str(&twin);
                text.push('\n');
                text.push_str(&entry);
            }
        }
        return;
    }
}

fn fast_entry_head(name: &str) -> String {
    format!("pub fn {}(", crate::rust_ir::ast::escape_ident(name))
}

/// The public entry over an i64 body and its exact twin.
fn exact_entry(name: &str, inputs: &[(String, Option<String>)], fast: &EntryAbi, exact: &EntryAbi) -> Option<String> {
    use crate::rust_ir::ast::{escape_ident, Expr};
    use crate::rust_ir::render::{render_expr, render_ty};
    let mut params = Vec::new();
    let mut fast_args = Vec::new();
    let mut exact_args = Vec::new();
    for ((input, _), (fast_kind, exact_kind)) in inputs.iter().zip(fast.inputs.iter().zip(&exact.inputs)) {
        let arg = escape_ident(input);
        params.push(format!("{arg}: {}", render_ty(&fast_kind.rust_ty().ok()?)));
        fast_args.push(if fast_kind.is_copy() { arg.clone() } else { format!("{arg}.clone()") });
        exact_args.push(if fast_kind == exact_kind {
            arg
        } else {
            render_expr(&numeric_boundary_value(&Expr::Raw(arg), fast_kind, exact_kind, input)?)
        });
    }
    let narrowed = if fast.result == exact.result {
        "__exact".to_string()
    } else {
        render_expr(&numeric_boundary_value(&Expr::Raw("__exact".into()), &exact.result, &fast.result, name)?)
    };
    let (open, close) = if fast.inputs.iter().all(ValueKind::is_send) && fast.result.is_send() {
        ("    emath_rt::execution::on_stack(move || {\n", "    })\n")
    } else {
        ("", "")
    };
    Some(format!(
        "pub fn {ident}({params}) -> Result<{ty}, String> {{\n{open}    let __native_entry = emath_rt::execution::Frame::hold()?;\n    let __native_value = match emath_fast_{name}({fast_args}) {{\n        Err(fault) if fault == {INT_LANE_FAULT:?} => {{\n            let __exact = {twin}({exact_args})?;\n            {narrowed}\n        }}\n        other => other?,\n    }};\n    __native_entry.check()?;\n    Ok(__native_value)\n{close}}}\n",
        ident = escape_ident(name),
        params = params.join(", "),
        ty = render_ty(&fast.result.rust_ty().ok()?),
        fast_args = fast_args.join(", "),
        twin = exact_twin_name(name),
        exact_args = exact_args.join(", "),
    ))
}

/// A carrier's exact counterpart: Int widens to `ExactInt`; carriers the
/// twin cannot take return `None`.
fn exact_kind(kind: &ValueKind) -> Option<ValueKind> {
    match kind {
        ValueKind::I64 => Some(ValueKind::ExactInt),
        ValueKind::ExactInt | ValueKind::F64 | ValueKind::Rational | ValueKind::Bool => Some(kind.clone()),
        ValueKind::Vector(inner) => exact_kind(inner).map(|inner| ValueKind::Vector(Box::new(inner))),
        _ => None,
    }
}

fn exact_abi(abi: &EntryAbi) -> Option<EntryAbi> {
    Some(EntryAbi {
        inputs: abi.inputs.iter().map(exact_kind).collect::<Option<_>>()?,
        result: exact_kind(&abi.result)?,
    })
}

/// Whether every op renders over exact carriers: scalars, sequences,
/// branches, frames and calls. Records, closures, code and buffers keep
/// the i64 lane's refusal.
fn exact_body(program: &emath_exec_ir::EmirProgram) -> bool {
    use emath_exec_ir::EmirOp;
    program.ops.iter().all(|(op, _)| match op {
        EmirOp::ConstF64(_)
        | EmirOp::ConstI64(_)
        | EmirOp::ConstExactInt(_)
        | EmirOp::ConstBool(_)
        | EmirOp::LoadInput(_)
        | EmirOp::F64Add(..)
        | EmirOp::F64Sub(..)
        | EmirOp::F64Mul(..)
        | EmirOp::F64Div(..)
        | EmirOp::Neg(_)
        | EmirOp::ExactIntCall { .. }
        | EmirOp::Lt(..)
        | EmirOp::Le(..)
        | EmirOp::Gt(..)
        | EmirOp::Ge(..)
        | EmirOp::Eq(..)
        | EmirOp::Ne(..)
        | EmirOp::And(..)
        | EmirOp::Or(..)
        | EmirOp::Not(_)
        | EmirOp::ListCreate(_)
        | EmirOp::ListConcat(_)
        | EmirOp::VectorLength(_)
        | EmirOp::VectorIndex { .. }
        | EmirOp::Refuse(_)
        | EmirOp::RefuseValue(_)
        | EmirOp::CallSelf { .. }
        | EmirOp::CallSibling { .. } => true,
        EmirOp::Branch { then_body, else_body, .. } => exact_body(then_body) && exact_body(else_body),
        EmirOp::CallFrame { body, .. } | EmirOp::Collect { body, .. } => exact_body(body),
        EmirOp::Iterate { body, stop, .. } => exact_body(body) && stop.as_ref().is_none_or(exact_body),
        _ => false,
    })
}

/// The entry parameters for one function: each lowered input with its
/// declared carrier signature (`None` = untyped, the numeric lane's Int).
fn entry_inputs(
    tree: &SyntaxTree,
    name: &str,
    inputs: &[String],
    objects: &std::collections::BTreeSet<String>,
) -> Vec<(String, Option<String>)> {
    let declared = tree
        .items
        .iter()
        .find_map(|item| match item {
            emath_core::tree::Item::Declaration(decl) if decl.name == name => Some(
                emath_exec_ir::constructor_emir::section_typed_fields(decl, "inputs"),
            ),
            _ => None,
        })
        .unwrap_or_default();
    inputs
        .iter()
        .map(|input| {
            let signature = declared
                .iter()
                .find(|(declared, _)| declared == input)
                .and_then(|(_, ty)| {
                    emath_exec_ir::constructor_emir::constructor_type_signature(ty, objects)
                });
            (input.clone(), signature)
        })
        .collect()
}

/// A function's first declared output with its carrier signature, when
/// the interchange maps it.
fn declared_output(
    tree: &SyntaxTree,
    name: &str,
    objects: &std::collections::BTreeSet<String>,
) -> Option<(String, String)> {
    tree.items.iter().find_map(|item| match item {
        emath_core::tree::Item::Declaration(decl) if decl.name == name => {
            let outputs = emath_exec_ir::constructor_emir::section_typed_fields(decl, "outputs");
            let (output, ty) = outputs.first()?;
            let signature =
                emath_exec_ir::constructor_emir::constructor_type_signature(ty, objects)?;
            Some((output.clone(), signature))
        }
        _ => None,
    })
}

/// Collect every sibling name reachable in a program's ops, including
/// nested control/collection/frame bodies (a call can sit under any
/// binder): recursion-cycle edges (`CallSibling`) always, and the
/// callees of named inlined frames when `frames` is set.
fn collect_named_calls(
    program: &emath_exec_ir::EmirProgram,
    frames: bool,
    out: &mut Vec<String>,
) {
    use emath_exec_ir::EmirOp;
    for (op, _) in &program.ops {
        match op {
            EmirOp::CallSibling { name, .. } => out.push(name.clone()),
            EmirOp::Branch {
                then_body,
                else_body,
                ..
            } => {
                collect_named_calls(then_body, frames, out);
                collect_named_calls(else_body, frames, out);
            }
            EmirOp::CallFrame { body, callee, .. } => {
                if frames && let Some(callee) = callee {
                    out.push(callee.clone());
                }
                collect_named_calls(body, frames, out);
            }
            EmirOp::ProgramLiteral { body, .. }
            | EmirOp::Fold { body, .. }
            | EmirOp::Collect { body, .. } => collect_named_calls(body, frames, out),
            EmirOp::Iterate { body, stop, .. } => {
                collect_named_calls(body, frames, out);
                if let Some(stop) = stop {
                    collect_named_calls(stop, frames, out);
                }
            }
            _ => {}
        }
    }
}
