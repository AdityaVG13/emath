/// `inspect <dir>`: print the committed artifact manifest.
fn inspect_cmd(args: &[String]) -> u8 {
    let Some(dir) = first_positional(args) else {
        return usage("inspect <artifact-dir>");
    };
    let dir = PathBuf::from(dir);
    let root = dir.join("emath");
    let Ok(entries) = std::fs::read_dir(&root) else {
        eprintln!(
            "error: E-TLT-005: no `emath/` state directory under {}",
            dir.display()
        );
        return EXIT_USAGE;
    };
    let mut inspected = 0;
    for entry in entries.flatten() {
        if !entry.path().is_dir() {
            continue;
        }
        let manifest = entry.path().join("manifest.json");
        let Ok(bytes) = std::fs::read(&manifest) else {
            eprintln!(
                "error: E-TLT-005: missing manifest at {}",
                manifest.display()
            );
            return EXIT_REFUSED;
        };
        let text = String::from_utf8_lossy(&bytes);
        println!("artifact {}:", entry.file_name().to_string_lossy());
        println!("{text}");
        inspected += 1;
    }
    if inspected == 0 {
        eprintln!("error: E-TLT-005: no artifacts under {}", root.display());
        EXIT_USAGE
    } else {
        EXIT_OK
    }
}

/// `diff <a.emath> <b.emath>`: fingerprint comparison of parse-admitted sources.
fn diff_cmd(args: &[String]) -> u8 {
    let positional = positional_args(args);
    let Some(a) = positional.first() else {
        return usage("diff <a.emath> <b.emath>");
    };
    let Some(b) = positional.get(1) else {
        return usage("diff <a.emath> <b.emath>");
    };
    let id_a = fingerprint(a);
    let id_b = fingerprint(b);
    match (id_a, id_b) {
        (Ok(id_a), Ok(id_b)) => {
            println!("diff: {a} {}", id_a.0);
            println!("diff: {b} {}", id_b.0);
            if id_a == id_b {
                println!("diff: identical");
                EXIT_OK
            } else {
                println!("diff: differ");
                EXIT_REFUSED
            }
        }
        (Err(()), _) | (_, Err(())) => EXIT_REFUSED,
    }
}

/// Content id of a parse-admitted source; diagnostics printed on refusal.
fn fingerprint(file: &str) -> Result<emath_core::ContentId, ()> {
    let mut session = CompilerSession::new(emath_core::limits::Limits::default());
    let Ok(package) = session.load_package(file) else {
        eprintln!("error: cannot read {file}");
        return Err(());
    };
    let result = session.check(package.file);
    print_diagnostics(&result.diagnostics);
    if result.diagnostics.has_errors() {
        return Err(());
    }
    let Ok(bytes) = std::fs::read(file) else {
        eprintln!("error: cannot read {file}");
        return Err(());
    };
    Ok(emath_core::content_id_of_str(&String::from_utf8_lossy(
        &bytes,
    )))
}

/// `doctor`: toolchain presence checks.
fn doctor_cmd(args: &[String]) -> u8 {
    if args.iter().any(|arg| arg == "--help" || arg == "-h") {
        println!(
            "doctor: checks rustc, cargo, rustfmt and clippy presence; exits 0 when all found"
        );
        return EXIT_OK;
    }
    let checks = [
        ("rustc", "rustc --version"),
        ("cargo", "cargo --version"),
        ("rustfmt", "rustfmt --version"),
        ("clippy", "cargo clippy --version"),
    ];
    let mut ok = true;
    for (name, probe) in checks {
        if let Some(version) = probe_program(probe) {
            println!("doctor: {name}: ok ({version})");
        } else {
            println!("doctor: {name}: MISSING");
            ok = false;
        }
    }
    if ok {
        EXIT_OK
    } else {
        EXIT_REFUSED
    }
}

fn probe_program(command: &str) -> Option<String> {
    let mut parts = command.split_whitespace();
    let program = parts.next()?;
    let output = Command::new(program).args(parts).output().ok()?;
    if output.status.success() {
        let text = String::from_utf8_lossy(&output.stdout).trim().to_string();
        Some(text.lines().next().unwrap_or(&text).to_string())
    } else {
        None
    }
}

/// `vendor --out <dir>`: offline dependency snapshot (zero third-party deps).
fn vendor_cmd(args: &[String]) -> u8 {
    let Some(out) = flag_value("--out", args).or_else(|| flag_value("-o", args)) else {
        return usage("vendor --out <dir>");
    };
    let lock = upstream_lock_path();
    let Ok(bytes) = std::fs::read(&lock) else {
        eprintln!(
            "error: E-TLT-007: upstream lock missing at {}",
            lock.display()
        );
        return EXIT_USAGE;
    };
    let text = String::from_utf8_lossy(&bytes);
    let entry_count = text.matches("      \"id\": \"").count();
    let mut object = JsonWriter::object();
    object.string("schema", "emath.vendor.v1");
    object.string("source", UPSTREAM_LOCK_REL);
    let source_id = content_id_of_str(&text).0;
    object.string("source_id", &source_id);
    object.int("upstream_pins", u64::try_from(entry_count).unwrap_or(0));
    object.int("third_party_deps", 0);
    object.bool("offline", true);
    let out_dir = PathBuf::from(out);
    if std::fs::create_dir_all(&out_dir).is_err() {
        eprintln!("error: cannot create {}", out_dir.display());
        return EXIT_USAGE;
    }
    let target = out_dir.join("vendor-manifest.json");
    let body = object.finish();
    if std::fs::write(&target, body.clone()).is_err() {
        eprintln!("error: cannot write {}", target.display());
        return EXIT_USAGE;
    }
    println!("vendor: wrote {body}");
    EXIT_OK
}

/// `provider list|inspect <id>|test <id>`.
fn provider_cmd(args: &[String]) -> u8 {
    let Some(sub) = args.first() else {
        return usage("provider list|inspect <id>|test <id>");
    };
    match sub.as_str() {
        "list" => {
            for (id, capability, status) in PROVIDERS {
                println!("provider {id}: {capability} [{status}]");
            }
            EXIT_OK
        }
        "inspect" => {
            let Some(id) = args.get(1) else {
                return usage("provider inspect <id>");
            };
            let Some((_, capability, status)) =
                PROVIDERS.iter().find(|(candidate, _, _)| candidate == id)
            else {
                eprintln!("error: E-PROV-001: unknown provider `{id}`");
                return EXIT_USAGE;
            };
            let mut object = JsonWriter::object();
            object.string("schema", "emath.provider-descriptor.v1");
            object.string("id", id);
            object.string("capability", capability);
            object.string("status", status);
            println!("{}", object.finish());
            EXIT_OK
        }
        "test" => {
            let Some(id) = args.get(1) else {
                return usage("provider test <id>");
            };
            let Some((_, _, status)) = PROVIDERS.iter().find(|(candidate, _, _)| candidate == id)
            else {
                eprintln!("error: E-PROV-001: unknown provider `{id}`");
                return EXIT_USAGE;
            };
            if *status == "implemented" {
                println!(
                    "provider {id}: negative control suite: ok (deterministic artifact control)"
                );
                EXIT_OK
            } else {
                eprintln!(
                    "error: E-PROV-002: provider `{id}` is not yet available in the Phase 1 subset"
                );
                EXIT_REFUSED
            }
        }
        _ => usage("provider list|inspect <id>|test <id>"),
    }
}

/// `fork status|sync [--dry-run]`.
fn fork_cmd(args: &[String]) -> u8 {
    let Some(sub) = args.first() else {
        return usage("fork status|sync [--dry-run]");
    };
    let lock = upstream_lock_path();
    let Ok(bytes) = std::fs::read(&lock) else {
        eprintln!(
            "error: E-TLT-007: upstream lock missing at {}",
            lock.display()
        );
        return EXIT_USAGE;
    };
    let text = String::from_utf8_lossy(&bytes);
    match sub.as_str() {
        "status" => {
            for id in lock_ids(&text) {
                println!("fork {id}: pinned (lock {})", content_id_of_str(&text).0);
            }
            EXIT_OK
        }
        "sync" => {
            if args.iter().any(|arg| arg == "--dry-run") {
                println!(
                    "sync: dry-run: {} upstream pins unchanged (offline)",
                    lock_ids(&text).len()
                );
                EXIT_OK
            } else {
                eprintln!("error: E-TLT-006: network/source sync is disabled in Phase 1 (offline-first); use --dry-run");
                EXIT_REFUSED
            }
        }
        _ => usage("fork status|sync [--dry-run]"),
    }
}

/// Extracts quoted `"id": "..."` values from the lock document.
fn lock_ids(text: &str) -> Vec<String> {
    let mut ids = Vec::new();
    for line in text.lines() {
        let Some(rest) = line.trim().strip_prefix("\"id\": \"") else {
            continue;
        };
        if let Some(end) = rest.find('"') {
            ids.push(rest[..end].to_string());
        }
    }
    ids
}

/// `agent check|plan|build <file> ...`: structured envelope over the real
/// pipeline. The agent surface cannot bypass admission or artifact checks:
/// it renders the same session/build results as the interactive commands.
fn agent_cmd(args: &[String]) -> u8 {
    let Some(sub) = args.first() else {
        return usage("agent check|plan|build <file.emath> [--out <dir>]");
    };
    let positional = positional_args(&args[1..]);
    let file = positional.first();
    match sub.as_str() {
        "check" => {
            let Some(file) = file else {
                return usage("agent check <file.emath>");
            };
            let (diagnostics, package_id) = run_check(file);
            let admitted = !diagnostics.has_errors();
            let mut object = JsonWriter::object();
            object.string("schema", "emath.agent.v1");
            object.string("command", "check");
            object.bool("admitted", admitted);
            object.string("package", &package_id);
            object.int("diagnostics", diagnostics.len() as u64);
            let mut lines = String::new();
            for item in diagnostics.items() {
                lines.push_str(item.code);
                lines.push_str(": ");
                lines.push_str(&item.message);
                lines.push_str("; ");
            }
            object.string("diagnostics_text", &lines);
            println!("{}", object.finish());
            if admitted {
                EXIT_OK
            } else {
                EXIT_REFUSED
            }
        }
        "plan" => {
            let Some(file) = file else {
                return usage("agent plan <file.emath>");
            };
            let mut session = CompilerSession::new(emath_core::limits::Limits::default());
            let Ok(package) = session.load_package(file) else {
                eprintln!("error: cannot read {file}");
                return EXIT_USAGE;
            };
            let result = session.plan(package.file);
            let mut object = JsonWriter::object();
            object.string("schema", "emath.agent.v1");
            object.string("command", "plan");
            object.bool("admitted", !result.diagnostics.has_errors());
            object.int("goals", result.package.goals.len() as u64);
            object.int("plans", result.plans.len() as u64);
            let mut goals = String::new();
            for goal in &result.package.goals {
                goals.push_str(goal.kind.as_str());
                goals.push(' ');
                goals.push_str(goal.target.as_str());
                goals.push(' ');
            }
            object.string("goals", &goals);
            println!("{}", object.finish());
            if result.diagnostics.has_errors() {
                EXIT_REFUSED
            } else {
                EXIT_OK
            }
        }
        "build" => {
            let Some(file) = file else {
                return usage("agent build <file.emath> --out <dir>");
            };
            let Some(out) = flag_value("--out", args).or_else(|| flag_value("-o", args)) else {
                return usage("agent build <file.emath> --out <dir>");
            };
            match build_file(
                file,
                PathBuf::from(out),
                BuildOptions {
                    verify_generated_crate: false,
                },
            ) {
                Ok(report) => {
                    let mut object = JsonWriter::object();
                    object.string("schema", "emath.agent.v1");
                    object.string("command", "build");
                    object.string("artifact_id", &report.artifact_id.0);
                    object.string("package_id", &report.package_id.0);
                    object.string("crate", &report.crate_name);
                    object.string("artifact_dir", &report.artifact_dir.display().to_string());
                    println!("{}", object.finish());
                    EXIT_OK
                }
                Err(error) => {
                    eprintln!("error: {error}");
                    classify_build_error(&error)
                }
            }
        }
        _ => usage("agent check|plan|build <file.emath> [--out <dir>]"),
    }
}

/// Mirrors `crate::run_check` for the agent envelope (same admission path).
fn run_check(path: &str) -> (emath_core::Diagnostics, String) {
    let mut session = CompilerSession::new(emath_core::limits::Limits::default());
    let Ok(package) = session.load_package(path) else {
        return (emath_core::Diagnostics::new(), String::new());
    };
    let result = session.check(package.file);
    (result.diagnostics, result.package.content_id().0)
}

/// Maps a build error to the conventional exit class.
fn classify_build_error(error: &dyn std::fmt::Display) -> u8 {
    let text = error.to_string();
    if text.contains("admission refused") {
        EXIT_REFUSED
    } else {
        EXIT_USAGE
    }
}

fn positional_args(args: &[String]) -> Vec<String> {
    args.iter()
        .filter(|arg| !arg.starts_with('-'))
        .cloned()
        .collect()
}

fn first_positional(args: &[String]) -> Option<String> {
    positional_args(args).first().cloned()
}

fn flag_value(flag: &str, args: &[String]) -> Option<String> {
    args.iter()
        .position(|arg| arg == flag)
        .and_then(|index| args.get(index + 1))
        .cloned()
}

fn usage(message: &str) -> u8 {
    eprintln!("usage: emath {message}");
    eprintln!("run `emath help` for the full command list");
    EXIT_USAGE
}

